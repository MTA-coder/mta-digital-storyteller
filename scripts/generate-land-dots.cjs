const sharp = require('sharp')
const path = require('path')
const fs = require('fs')

/**
 * Generate evenly-distributed "dotted continent" coordinates for the 3D globe.
 *
 * Reads an equirectangular land/water mask (water = white, land = dark),
 * distributes candidate points across the sphere with a Fibonacci lattice
 * (equal-area — no clustering at the poles), keeps the ones that fall on
 * land, and emits a compact flat [lat, lng, lat, lng, ...] array as a
 * TypeScript module. This runs at build time so the runtime never has to
 * decode an image or read pixels on the main thread.
 *
 * Usage:  node scripts/generate-land-dots.cjs
 * Input:  scripts/assets/land-mask.png   (equirectangular, water bright / land dark)
 * Output: src/components/globe/landDots.ts
 */

const MASK = path.resolve(__dirname, 'assets/land-mask.png')
const OUT = path.resolve(__dirname, '../src/components/globe/landDots.ts')

// Number of candidate points spread over the whole sphere. ~29% of Earth is
// land, so ~28000 candidates yields roughly 8000 land dots — a dense, crisp
// silhouette that still renders in a single draw call.
const SAMPLES = 28000
// Land where the mask's grayscale value is below this (0 = land, 255 = water).
const LAND_THRESHOLD = 120

async function main() {
  if (!fs.existsSync(MASK)) {
    console.error(`✗ Land mask not found at ${MASK}`)
    console.error('  Provide an equirectangular land/water PNG (water bright, land dark).')
    process.exit(1)
  }

  const { data, info } = await sharp(MASK)
    .grayscale()
    .raw()
    .toBuffer({ resolveWithObject: true })
  const W = info.width
  const H = info.height
  const C = info.channels

  const sampleMask = (lat, lng) => {
    let x = Math.floor(((lng + 180) / 360) * W)
    let y = Math.floor(((90 - lat) / 180) * H)
    x = Math.max(0, Math.min(W - 1, x))
    y = Math.max(0, Math.min(H - 1, y))
    return data[(y * W + x) * C]
  }

  const golden = Math.PI * (3 - Math.sqrt(5)) // golden angle
  const dots = []

  for (let i = 0; i < SAMPLES; i++) {
    // Fibonacci sphere -> even coverage
    const y = 1 - (i / (SAMPLES - 1)) * 2 // 1 .. -1
    const r = Math.sqrt(Math.max(0, 1 - y * y))
    const theta = i * golden
    const x = Math.cos(theta) * r
    const z = Math.sin(theta) * r

    const lat = Math.asin(y) * (180 / Math.PI)
    const lng = Math.atan2(z, x) * (180 / Math.PI)

    if (sampleMask(lat, lng) < LAND_THRESHOLD) {
      dots.push(Math.round(lat * 10) / 10, Math.round(lng * 10) / 10)
    }
  }

  const count = dots.length / 2
  const header = `// AUTO-GENERATED by scripts/generate-land-dots.cjs — do not edit by hand.
// Flat [lat, lng, lat, lng, ...] land coordinates sampled from an
// equirectangular land mask via a Fibonacci lattice (equal-area).
// Regenerate with: node scripts/generate-land-dots.cjs
`
  const body = `export const landDotCount = ${count}

export const landDots: number[] = [\n${chunk(dots, 16)}\n]\n`

  fs.writeFileSync(OUT, header + '\n' + body, 'utf-8')
  const sizeKB = (fs.statSync(OUT).size / 1024).toFixed(1)
  console.log(`✓ Wrote ${count} land dots -> ${path.relative(process.cwd(), OUT)} (${sizeKB} KB)`)
}

// Pretty-print the flat array, `per` numbers per line, 2-space indent.
function chunk(arr, per) {
  const lines = []
  for (let i = 0; i < arr.length; i += per) {
    lines.push('  ' + arr.slice(i, i + per).join(', ') + ',')
  }
  return lines.join('\n')
}

main().catch((err) => {
  console.error('Error:', err)
  process.exit(1)
})
